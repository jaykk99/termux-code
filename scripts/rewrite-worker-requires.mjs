// Post-build step: rewrite bare require() calls for Node.js builtins in the
// OpenNext worker output to ESM imports.
//
// Problem: Next's webpack server build (target=node) emits free require()
// calls for Node builtins (require("fs"), require("node:fs"),
// require("path"), ...). OpenNext's esbuild step carries those calls into
// the worker bundle (handler.mjs). The Pages production worker is ESM, and
// in that scope there is no global require, so the first such call on any
// executed path throws `Dynamic require of "X" is not supported` and the
// worker never boots (Cloudflare error 1101 on every route). The sequence
// so far proves it is whack-a-mole at the source level: neutralizing
// Next's node:crypto extension (PR #10) just moved the throw to node:fs
// (next-server.js), and after fs the next builtin in import order would
// throw instead. Patching one source file at a time cannot win.
//
// Fix: after `opennextjs-cloudflare build`, rewrite every literal
// require() of a Node builtin in the worker's ESM output files to an ESM
// import of the same builtin, which workerd resolves under nodejs_compat
// (verified in local workerd: import("node:fs"), import("node:path"),
// import("node:crypto") all resolve; only child_process has no workerd
// implementation at all, so it is rerouted to a tiny shim that throws a
// plain "unavailable on Workers" error if ever called -- the app's own
// run_terminal path already returns an honest unavailable message on
// Workers without calling exec, so the shim is never reached on Pages).
//
// Safety: the rewrite is asserted, not blind.
//  - Only files that look ESM (contain an import/export statement) are
//    rewritten; anything else with a builtin require fails the build
//    loudly instead of being silently skipped.
//  - After rewriting, the script re-scans every processed file and fails
//    loudly if any literal builtin require remains (a quoting or
//    formatting form the pattern missed).
//  - Non-builtin requires (e.g. @builder.io/partytown/integration) are
//    left alone and reported; they are out of scope here.
//  - The script is idempotent: a re-run finds no builtin requires left
//    and leaves every file byte-identical (the import prelude is only
//    added when at least one replacement happens).
//  - It only touches files under .open-next (gitignored build output
//    that the Pages build regenerates), never committed source and never
//    node_modules. Plain `next build` / `next dev` do not run it.
//
// Runs as part of `npm run build:cf`, after the adapter build.
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

// Node.js builtins (base names, without the node: prefix). Subpaths such
// as fs/promises or stream/web are matched via the same base name.
export const BUILTINS = new Set([
  'assert', 'async_hooks', 'buffer', 'child_process', 'cluster', 'console',
  'constants', 'crypto', 'dgram', 'diagnostics_channel', 'dns', 'domain',
  'events', 'fs', 'http', 'http2', 'https', 'inspector', 'module', 'net',
  'os', 'path', 'perf_hooks', 'process', 'punycode', 'querystring',
  'readline', 'repl', 'stream', 'string_decoder', 'sys', 'timers', 'tls',
  'trace_events', 'tty', 'url', 'util', 'v8', 'vm', 'wasi',
  'worker_threads', 'zlib',
]);

// Matches a literal require("spec") / require('spec') call, with optional
// whitespace. Group 1 is the specifier.
const REQUIRE_RE = /require\(\s*["']([^"']+)["']\s*\)/g;
const ESM_MARKER_RE = /(^|\n)\s*import[\s({*]|export\s*(default|\{)/;

export const CHILD_PROCESS_SHIM = `// Generated by scripts/rewrite-worker-requires.mjs (build output only).
// child_process has no Cloudflare Workers implementation: even an ESM
// import of it throws "No such module", so requires of it are rerouted
// here instead of to a real import. Every export throws a plain error if
// called; the app's run_terminal path already returns an honest
// "unavailable on Workers" message without calling exec, so this shim is
// never reached on Pages -- it exists so the worker bundle loads.
function unavailable() {
  throw new Error('child_process is unavailable in Cloudflare Workers');
}
export const exec = unavailable;
export const execSync = unavailable;
export const spawn = unavailable;
export const spawnSync = unavailable;
export const execFile = unavailable;
export const execFileSync = unavailable;
export const fork = unavailable;
export default { exec, execSync, spawn, spawnSync, execFile, execFileSync, fork };
`;

const SHIM_FILENAME = '__termux_child_process_shim.mjs';

function parseSpecifier(spec) {
  const m = /^(?:node:)?([a-z0-9_]+)(\/.*)?$/.exec(spec);
  if (!m) return null;
  return { base: m[1], subpath: m[2] || '' };
}

// Rewrites one file's content. Returns { content, counts, nonBuiltins }.
// counts maps canonical import specifier -> number of replacements.
// Throws on a builtin require in a non-ESM file, or on an identifier
// collision it cannot resolve.
export function rewriteContent(content, fileLabel) {
  const counts = new Map();
  const nonBuiltins = new Set();
  const usedIdentifiers = new Set();
  // Collect identifiers already present so generated ones cannot collide.
  for (const m of content.matchAll(/[A-Za-z_$][A-Za-z0-9_$]*/g)) {
    usedIdentifiers.add(m[0]);
  }
  const identifiers = new Map(); // canonical spec -> identifier
  const shimNeeded = { value: false };

  function identifierFor(canonical, isShim) {
    if (identifiers.has(canonical)) return identifiers.get(canonical);
    const base = isShim
      ? '__termux_child_process_shim'
      : `__termux_node_${canonical.replace(/^node:/, '').replace(/[^A-Za-z0-9]/g, '_')}`;
    let id = base;
    let n = 2;
    while (usedIdentifiers.has(id)) id = `${base}_${n++}`;
    usedIdentifiers.add(id);
    identifiers.set(canonical, id);
    return id;
  }

  let foundBuiltin = false;
  const rewritten = content.replace(REQUIRE_RE, (whole, spec) => {
    const parsed = parseSpecifier(spec);
    if (!parsed || !BUILTINS.has(parsed.base)) {
      nonBuiltins.add(spec);
      return whole;
    }
    foundBuiltin = true;
    if (parsed.base === 'child_process') {
      shimNeeded.value = true;
      const id = identifierFor('__termux_child_process_shim', true);
      counts.set('__termux_child_process_shim', (counts.get('__termux_child_process_shim') || 0) + 1);
      return id;
    }
    const canonical = `node:${parsed.base}${parsed.subpath}`;
    const id = identifierFor(canonical, false);
    counts.set(canonical, (counts.get(canonical) || 0) + 1);
    return id;
  });

  if (!foundBuiltin) return { content, counts, nonBuiltins, changed: false };
  if (!ESM_MARKER_RE.test(content)) {
    throw new Error(
      `refusing to rewrite ${fileLabel}: it requires Node builtins but ` +
        `does not look like an ESM file, so an import prelude cannot be ` +
        `added safely; inspect it instead of shipping a broken worker`
    );
  }
  const imports = [];
  for (const [canonical, id] of identifiers) {
    if (canonical === '__termux_child_process_shim') {
      imports.push(`import * as ${id} from "./${SHIM_FILENAME}";`);
    } else {
      imports.push(`import * as ${id} from "${canonical}";`);
    }
  }
  return {
    content: imports.join('\n') + '\n' + rewritten,
    counts,
    nonBuiltins,
    changed: true,
    shimNeeded: shimNeeded.value,
  };
}

// Returns true if any literal builtin require remains in content.
export function hasBuiltinRequire(content) {
  for (const m of content.matchAll(REQUIRE_RE)) {
    const parsed = parseSpecifier(m[1]);
    if (parsed && BUILTINS.has(parsed.base)) return true;
  }
  return false;
}

function collectFiles(dir, out) {
  if (!existsSync(dir)) return out;
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === 'node_modules' || entry.name === '.next') continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) collectFiles(full, out);
    else if (entry.isFile() && (full.endsWith('.mjs') || full.endsWith('.js'))) out.push(full);
  }
  return out;
}

export function main(repoRoot = process.cwd()) {
  const openNextDir = path.join(repoRoot, '.open-next');
  if (!existsSync(openNextDir)) {
    throw new Error(`.open-next output not found (run the adapter build first): ${openNextDir}`);
  }
  const files = collectFiles(openNextDir, []);
  const report = [];
  let totalReplacements = 0;
  for (const file of files) {
    const original = readFileSync(file, 'utf8');
    const { content, counts, nonBuiltins, changed, shimNeeded } = rewriteContent(original, file);
    if (!changed) continue;
    if (shimNeeded) {
      const shimPath = path.join(path.dirname(file), SHIM_FILENAME);
      writeFileSync(shimPath, CHILD_PROCESS_SHIM);
      report.push(`${path.relative(repoRoot, shimPath)}: wrote child_process shim`);
    }
    writeFileSync(file, content);
    // Assert: no literal builtin require may survive the rewrite.
    const after = readFileSync(file, 'utf8');
    if (hasBuiltinRequire(after)) {
      throw new Error(
        `rewrite incomplete for ${file}: a builtin require remains after ` +
          `rewriting; the pattern missed a formatting form, fix the script ` +
          `instead of shipping a worker that throws at boot`
      );
    }
    totalReplacements += [...counts.values()].reduce((a, b) => a + b, 0);
    const detail = [...counts.entries()].map(([spec, n]) => `${spec} x${n}`).join(', ');
    report.push(`${path.relative(repoRoot, file)}: rewrote ${detail}`);
    if (nonBuiltins.size > 0) {
      report.push(`  (left alone, non-builtin: ${[...nonBuiltins].join(', ')})`);
    }
  }
  for (const line of report) console.log(`rewrite-worker-requires: ${line}`);
  console.log(`rewrite-worker-requires: ${totalReplacements} builtin require(s) rewritten in ${report.length} step(s)`);
  return { report, totalReplacements };
}

const invokedAsScript =
  process.argv[1] &&
  import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href;
if (invokedAsScript) {
  const scriptDir = path.dirname(fileURLToPath(import.meta.url));
  main(path.join(scriptDir, '..'));
}
